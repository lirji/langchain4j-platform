CREATE TABLE USER_PROFILE_OWNER (
  OWNER_KEY CHAR(64) NOT NULL COMMENT '长度定界租户及用户身份的 SHA-256，按字节区分身份',
  TENANT_ID VARCHAR(128) NOT NULL COMMENT '服务端验证的租户标识，不用于大小写不敏感的鉴权查询',
  USER_ID VARCHAR(256) NOT NULL COMMENT '服务端验证的用户标识，画像仅限该用户',
  PRIMARY KEY (OWNER_KEY)
) COMMENT='用户长期画像的所有者及并发锁；清空内容后保留锁行';

CREATE TABLE USER_PROFILE_MEMORY (
  RECORD_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '数据库插入序号，确定稳定召回及容量淘汰顺序',
  OWNER_KEY CHAR(64) NOT NULL COMMENT '画像所有者键，所有读取及写入均限定此键',
  MEMORY_ID VARCHAR(128) NOT NULL COMMENT '兼容既有接口的记忆标识，不能作为跨用户唯一键',
  MEMORY_TEXT TEXT NOT NULL COMMENT '用户长期事实正文，不保存原始对话或模型状态',
  MEMORY_TYPE VARCHAR(128) NULL COMMENT '既有抽取契约的记忆类型，如 preference 或 attribute',
  CREATED_AT BIGINT NOT NULL COMMENT '抽取创建时间，UTC epoch 毫秒，不作为写入排序依据',
  SOURCE_CHAT_ID VARCHAR(256) NULL COMMENT '来源会话标识，用于溯源，不包含原始对话',
  PRIMARY KEY (RECORD_ID),
  KEY IDX_PROFILE_OWNER_ORDER (OWNER_KEY, RECORD_ID),
  CONSTRAINT FK_PROFILE_MEMORY_OWNER FOREIGN KEY (OWNER_KEY) REFERENCES USER_PROFILE_OWNER (OWNER_KEY)
) COMMENT='持久化用户长期记忆；同所有者事务内去重并限制条目数量';

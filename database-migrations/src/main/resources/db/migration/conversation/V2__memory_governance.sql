  AUDIT_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '审计游标，按此字段稳定分页',
  OWNER_KEY CHAR(64) NOT NULL COMMENT '服务端校验的租户用户所有者键',
  RECORD_ID BIGINT NOT NULL COMMENT '记忆记录号；用户级操作为0，不保留正文',
  ACTION_CODE VARCHAR(32) NOT NULL COMMENT '明确稳定的操作代码，不使用枚举ordinal',
  REVISION BIGINT NOT NULL COMMENT '操作之后的记录版本或用户代次',
  OCCURRED_AT BIGINT NOT NULL COMMENT '操作时间UTC epoch毫秒',
  PRIMARY KEY (AUDIT_ID),
  KEY IDX_PROFILE_AUDIT_OWNER (OWNER_KEY, AUDIT_ID),

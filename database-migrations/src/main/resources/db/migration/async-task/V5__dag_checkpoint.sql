CREATE TABLE ASYNC_TASK_DAG_CHECKPOINT (
  TASK_ID VARCHAR(128) NOT NULL PRIMARY KEY COMMENT '中央任务ID，身份和可见性由父任务控制',
  REVISION BIGINT NOT NULL COMMENT '单调CAS版本，拒绝迟到快照',
  STATE_JSON MEDIUMTEXT NOT NULL COMMENT '检查点v1，含预算和有界节点结果，禁止凭据或运行时对象',
  UPDATED_AT BIGINT NOT NULL COMMENT '数据库接受快照的UTC毫秒时间',
  DELETED TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0正常，1已删除；父任务删除后不可访问',
  FOREIGN KEY (TASK_ID) REFERENCES ASYNC_TASK(TASK_ID) ON DELETE CASCADE
) COMMENT='只读DAG节点恢复权威快照，与任务租约同事务校验';

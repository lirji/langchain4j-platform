CREATE TABLE CHANNEL_INBOUND_INBOX (
  INBOX_ID CHAR(64) NOT NULL COMMENT '租户、渠道、外部消息标识的 SHA-256 去重键',
  TENANT_ID VARCHAR(128) NOT NULL COMMENT '服务端渠道配置绑定的租户',
  SOURCE_NAME VARCHAR(32) NOT NULL COMMENT '稳定渠道 code：feishu 或 dingtalk',
  MESSAGE_ID VARCHAR(256) NOT NULL COMMENT '渠道提供的稳定消息标识',
  PAYLOAD_HASH CHAR(64) NOT NULL COMMENT '规范化消息 JSON 的 SHA-256，检测同键异参数',
  PAYLOAD_JSON MEDIUMTEXT NOT NULL COMMENT '可重新执行的消息内容；不保存 JWT 或应用凭据',
  TRACE_ID VARCHAR(128) NULL COMMENT '接收链路标识，不参与权限判定',
  STATUS_CODE VARCHAR(16) NOT NULL COMMENT 'PENDING、RUNNING、SUCCEEDED、DEAD',
  ATTEMPTS INT NOT NULL DEFAULT 0 COMMENT '实际领取次数，重试有上限',
  LEASE_OWNER VARCHAR(128) NULL COMMENT '持有处理租约的实例标识',
  LEASE_EPOCH BIGINT NOT NULL DEFAULT 0 COMMENT '每次领取递增的 fencing 版本',
  LEASE_UNTIL BIGINT NOT NULL DEFAULT 0 COMMENT '租约到期 UTC epoch 毫秒',
  NEXT_ATTEMPT_AT BIGINT NOT NULL COMMENT '下次允许重试的 UTC epoch 毫秒',
  CREATED_AT BIGINT NOT NULL COMMENT '接收并持久化的 UTC epoch 毫秒',
  UPDATED_AT BIGINT NOT NULL COMMENT '最后状态变更的 UTC epoch 毫秒',
  ERROR_CODE VARCHAR(64) NULL COMMENT '稳定错误 code，不保存异常正文或消息内容',
  PRIMARY KEY (INBOX_ID),
  KEY IDX_INBOX_DISPATCH (TENANT_ID, SOURCE_NAME, STATUS_CODE, NEXT_ATTEMPT_AT, CREATED_AT),
  KEY IDX_INBOX_LEASE (TENANT_ID, SOURCE_NAME, STATUS_CODE, LEASE_UNTIL),
  CONSTRAINT CK_INBOX_STATUS CHECK (STATUS_CODE IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'DEAD'))
) COMMENT='渠道可靠入站收件箱；数据库持久化成功后 ACK，租约恢复与业务幂等分开治理';

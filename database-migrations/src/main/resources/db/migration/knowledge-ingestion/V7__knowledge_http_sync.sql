CREATE TABLE KNOWLEDGE_HTTP_SYNC (
  TENANT_KEY CHAR(64) NOT NULL COMMENT '租户SHA256摘要，保留租户大小写隔离',
  SOURCE_KEY CHAR(64) NOT NULL COMMENT '服务端配置来源ID的SHA256摘要',
  CONFIG_HASH CHAR(64) NOT NULL COMMENT '端点和执行身份摘要，凭据轮换不影响检查点',
  CURSOR_VALUE VARCHAR(1024) NOT NULL DEFAULT '' COMMENT '最近整页成功后的不透明来源游标',
  PENDING_JSON LONGTEXT NULL COMMENT '待处理页和固定入库版本快照；完成后清空，不保存令牌',
  ERROR_CODE VARCHAR(64) NULL COMMENT '脱敏错误码，失败时不推进游标',
  JOB_ID VARCHAR(64) NULL COMMENT '正在等待的知识入库任务标识',
  REVISION BIGINT NOT NULL DEFAULT 0 COMMENT '检查点CAS版本，拒绝过期执行器提交',
  LEASE_OWNER VARCHAR(64) NULL COMMENT '本轮随机执行权令牌',
  LEASE_UNTIL BIGINT NOT NULL DEFAULT 0 COMMENT 'UTC毫秒租约截止时间',
  NEXT_POLL_AT BIGINT NOT NULL DEFAULT 0 COMMENT 'UTC毫秒下次允许轮询时间',
  DELETED TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标记：0正常，1已删除',
  PRIMARY KEY (TENANT_KEY,SOURCE_KEY),
  CONSTRAINT CHK_HTTP_SYNC_DELETED CHECK (DELETED IN (0,1))
) COMMENT='HTTP知识源增量同步检查点与当前有界页恢复意图';
CREATE TABLE KNOWLEDGE_HTTP_SYNC_DOCUMENT (
  TENANT_KEY CHAR(64) NOT NULL COMMENT '租户SHA256摘要',
  SOURCE_KEY CHAR(64) NOT NULL COMMENT '来源ID的SHA256摘要',
  EXTERNAL_KEY CHAR(64) NOT NULL COMMENT '外部记录ID的SHA256摘要',
  SOURCE_REVISION BIGINT NOT NULL COMMENT '最近成功处理的外部单调递增版本',
  CONTENT_HASH CHAR(64) NOT NULL COMMENT '规范化标题与正文摘要，检测同版本异内容',
  DOCUMENT_VERSION BIGINT NOT NULL COMMENT '已确认的知识库文档版本；未入库的删除事件为0',
  DOCUMENT_ID VARCHAR(128) NOT NULL COMMENT '来源当前生命周期的文档ID；删除后重建使用新ID防迟到写入',
  EXTERNAL_ID VARCHAR(256) NOT NULL COMMENT '外部原始记录标识，用于定位来源记录；不保存正文',
  SOURCE_DELETED TINYINT NOT NULL COMMENT '来源删除墓碑：0有效，1已删除',
  DELETED TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标记：0正常，1已删除',
  PRIMARY KEY (TENANT_KEY,SOURCE_KEY,EXTERNAL_KEY),
  CONSTRAINT CHK_HTTP_SYNC_DOCUMENT_VERSION CHECK (SOURCE_REVISION > 0 AND DOCUMENT_VERSION >= 0 AND SOURCE_DELETED IN (0,1)),
  CONSTRAINT CHK_HTTP_SYNC_DOCUMENT_DELETED CHECK (DELETED IN (0,1))
) COMMENT='HTTP来源记录到知识文档的成功版本映射与去重依据';

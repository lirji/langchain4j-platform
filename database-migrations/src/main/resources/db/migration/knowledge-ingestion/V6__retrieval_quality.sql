CREATE TABLE KNOWLEDGE_QUALITY_DATASET (
  ID VARCHAR(64) NOT NULL COMMENT '评测集稳定标识',
  TENANT_KEY CHAR(64) NOT NULL COMMENT '认证租户SHA256摘要',
  REQUEST_KEY CHAR(64) NOT NULL COMMENT '创建用户与幂等键摘要',
  REQUEST_HASH CHAR(64) NOT NULL COMMENT '创建请求内容摘要',
  REVISION BIGINT NOT NULL COMMENT '编辑与基线选择的乐观版本',
  ACTIVE_RUN_ID VARCHAR(64) NULL COMMENT '当前执行租约，阻止同一评测集并发执行或编辑',
  BODY_JSON LONGTEXT NOT NULL COMMENT '评测定义与基线引用，不包含凭据',
  DELETED TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标记：0正常，1已删除',
  PRIMARY KEY (ID),
  UNIQUE KEY UK_QUALITY_DATASET_REQUEST (TENANT_KEY, REQUEST_KEY),
  KEY IDX_QUALITY_DATASET_PAGE (TENANT_KEY, DELETED, ID),
  CONSTRAINT CHK_QUALITY_DATASET_DELETED CHECK (DELETED IN (0,1))
) COMMENT='租户检索评测集，可编辑定义及当前基线';
CREATE TABLE KNOWLEDGE_QUALITY_RUN (
  ID VARCHAR(64) NOT NULL COMMENT '评测运行标识及稳定分页游标',
  TENANT_KEY CHAR(64) NOT NULL COMMENT '认证租户SHA256摘要',
  DATASET_ID VARCHAR(64) NOT NULL COMMENT '所属租户评测集',
  REQUEST_KEY CHAR(64) NOT NULL COMMENT '执行用户与幂等键摘要',
  REQUEST_HASH CHAR(64) NOT NULL COMMENT '执行命令内容摘要',
  STATUS VARCHAR(16) NOT NULL COMMENT 'RUNNING、SUCCEEDED或FAILED；终态禁止覆盖',
  DEADLINE_AT BIGINT NOT NULL COMMENT 'UTC毫秒租约截止时间，过期后允许显式终止',
  BODY_JSON LONGTEXT NOT NULL COMMENT '不可变输入快照及服务端计算的结果，不含令牌和命中正文',
  DELETED TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标记：0正常，1已删除',
  PRIMARY KEY (ID),
  UNIQUE KEY UK_QUALITY_RUN_REQUEST (TENANT_KEY, DATASET_ID, REQUEST_KEY),
  KEY IDX_QUALITY_RUN_PAGE (TENANT_KEY, DATASET_ID, DELETED, ID),
  CONSTRAINT CHK_QUALITY_RUN_STATUS CHECK (STATUS IN ('RUNNING','SUCCEEDED','FAILED')),
  CONSTRAINT CHK_QUALITY_RUN_DELETED CHECK (DELETED IN (0,1))
) COMMENT='检索评测历史，输入快照固定且终态只写一次';
CREATE TABLE KNOWLEDGE_QUALITY_AUDIT (
  ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '审计序号',
  TENANT_KEY CHAR(64) NOT NULL COMMENT '认证租户摘要',
  DATASET_ID VARCHAR(64) NOT NULL COMMENT '评测集标识',
  ACTOR VARCHAR(256) NOT NULL COMMENT '认证操作者',
  ACTION_CODE VARCHAR(32) NOT NULL COMMENT 'CREATE、EDIT、BASELINE、START、FINISH或ABANDON',
  SUBJECT_ID VARCHAR(64) NOT NULL COMMENT '本次操作的评测集或运行ID',
  OCCURRED_AT BIGINT NOT NULL COMMENT 'UTC毫秒审计时间',
  DELETED TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标记：0正常，1已删除',
  PRIMARY KEY (ID),
  KEY IDX_QUALITY_AUDIT_DATASET (TENANT_KEY, DATASET_ID, ID),
  CONSTRAINT CHK_QUALITY_AUDIT_DELETED CHECK (DELETED IN (0,1))
) COMMENT='评测定义、基线与执行生命周期审计，不复制问题正文';

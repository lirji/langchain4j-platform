-- 只扩展结构；新旧 worker 不可混跑并宣称总额度生效，启用前停止旧领取者。
CREATE TABLE KNOWLEDGE_INGESTION_ADMISSION (
  GUARD_ID INTEGER NOT NULL COMMENT '固定为1的领取事务守卫',
  GRANT_SEQUENCE BIGINT NOT NULL DEFAULT 0 COMMENT '全局单调领取序号，用于租户轮转',
  GLOBAL_LIMIT INTEGER NULL COMMENT '首次领取绑定的全局有效租约上限',
  TENANT_LIMIT INTEGER NULL COMMENT '首次领取绑定的单租户有效租约上限',
  PRIMARY KEY (GUARD_ID)
) COMMENT='知识库入库跨副本准入守卫与共享额度策略';
INSERT INTO KNOWLEDGE_INGESTION_ADMISSION (GUARD_ID, GRANT_SEQUENCE) VALUES (1,0);
CREATE TABLE KNOWLEDGE_INGESTION_TENANT_TURN (
  TENANT_ID VARCHAR(128) NOT NULL COMMENT '与任务库一致的租户标识',
  LAST_GRANTED BIGINT NOT NULL COMMENT '该租户最近一次获准执行的全局序号',
  PRIMARY KEY (TENANT_ID)
) COMMENT='知识库入库租户公平轮转状态，重启后继续沿用';
CREATE INDEX IDX_INGESTION_CLAIM ON KNOWLEDGE_INGESTION_JOB (DELETED, STATUS, LEASE_OWNER, TENANT_ID, CREATED_AT);
CREATE INDEX IDX_INGESTION_ACTIVE ON KNOWLEDGE_INGESTION_JOB (DELETED, STATUS, TENANT_ID, LEASE_UNTIL);

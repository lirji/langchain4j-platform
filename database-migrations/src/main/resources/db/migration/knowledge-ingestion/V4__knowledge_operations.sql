CREATE TABLE KNOWLEDGE_OPERATION_FEEDBACK (
  ID VARCHAR(64) NOT NULL COMMENT '时间前缀加随机反馈标识，同时作为稳定分页游标',
  TENANT_KEY CHAR(64) NOT NULL COMMENT '租户标识SHA256，避免数据库排序规则混淆租户',
  AUTHOR_KEY CHAR(64) NOT NULL COMMENT '提交用户SHA256，普通用户只读自己的反馈',
  DOCUMENT_ID VARCHAR(256) NULL COMMENT '用户反馈关联的文档ID，只用于本租户运营归因',
  REASON_CODE VARCHAR(32) NOT NULL COMMENT 'NO_ANSWER、INCORRECT或HELPFUL反馈类别',
  REQUEST_KEY CHAR(64) NOT NULL COMMENT '用户和幂等键的长度定界摘要',
  REQUEST_HASH CHAR(64) NOT NULL COMMENT '原始请求内容摘要，拒绝同键不同请求',
  BODY_JSON LONGTEXT NOT NULL COMMENT '语言中立反馈JSON；包含问题、类别、评论及关联文档',
  PRIMARY KEY (ID),
  UNIQUE KEY UK_OPERATION_FEEDBACK_REQUEST (TENANT_KEY, REQUEST_KEY),
  KEY IDX_OPERATION_FEEDBACK_TENANT (TENANT_KEY, ID),
  KEY IDX_OPERATION_FEEDBACK_DOCUMENT (TENANT_KEY, DOCUMENT_ID, REASON_CODE),
  KEY IDX_OPERATION_FEEDBACK_AUTHOR (TENANT_KEY, AUTHOR_KEY, ID)
) COMMENT='用户主动提交的知识反馈，不自动收集完整对话';
CREATE TABLE KNOWLEDGE_OPERATION_CANDIDATE (
  ID VARCHAR(64) NOT NULL COMMENT '运营候选标识及稳定分页游标',
  TENANT_KEY CHAR(64) NOT NULL COMMENT '服务端认证租户摘要',
  REQUEST_KEY CHAR(64) NOT NULL COMMENT '创建用户和幂等键的摘要',
  REQUEST_HASH CHAR(64) NOT NULL COMMENT '原始创建命令摘要',
  REVISION BIGINT NOT NULL COMMENT '乐观版本，所有编辑与状态流转必须匹配',
  BODY_JSON LONGTEXT NOT NULL COMMENT '候选内容、用例、评测、审核及发布状态的语言中立快照',
  PRIMARY KEY (ID),
  UNIQUE KEY UK_OPERATION_CANDIDATE_REQUEST (TENANT_KEY, REQUEST_KEY),
  KEY IDX_OPERATION_CANDIDATE_TENANT (TENANT_KEY, ID)
) COMMENT='知识运营候选权威快照；索引仅由通过审核的发布任务生成';
CREATE TABLE KNOWLEDGE_OPERATION_AUDIT (
  ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '审计序号',
  TENANT_KEY CHAR(64) NOT NULL COMMENT '认证租户摘要',
  CANDIDATE_ID VARCHAR(64) NOT NULL COMMENT '同租户候选标识',
  ACTOR VARCHAR(256) NOT NULL COMMENT '执行操作的已认证用户',
  ACTION_CODE VARCHAR(32) NOT NULL COMMENT '稳定业务操作代码',
  REVISION BIGINT NOT NULL COMMENT '操作后的候选版本',
  OCCURRED_AT BIGINT NOT NULL COMMENT 'UTC epoch毫秒操作时间',
  PRIMARY KEY (ID),
  UNIQUE KEY UK_OPERATION_AUDIT_REVISION (TENANT_KEY, CANDIDATE_ID, REVISION)
) COMMENT='候选状态变更审计，与候选写入同事务且不复制正文';
CREATE TABLE KNOWLEDGE_OPERATION_RELEASE (
  TENANT_KEY CHAR(64) NOT NULL COMMENT '认证租户摘要',
  DOCUMENT_ID VARCHAR(128) NOT NULL COMMENT '运营生成的稳定文档ID',
  DOCUMENT_VERSION BIGINT NOT NULL COMMENT '待发布文档版本，按现有registry递增',
  CANDIDATE_ID VARCHAR(64) NOT NULL COMMENT '唯一拥有此版本发布权的候选',
  PRIMARY KEY (TENANT_KEY, DOCUMENT_ID, DOCUMENT_VERSION)
) COMMENT='运营发布版本占位；失败恢复保留占位，阻止另一候选抢占同版本';
